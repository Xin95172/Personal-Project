    # 【核心防呆】處理老師提到的 T=365 年化問題。
    # 如果 T <= 0 (結算日)，分母 sqrt(T) 會導致 float division by zero。
    if T <= 0 or sigma <= 0:
        return 0

    d1 = (math.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * math.sqrt(T))
    d2 = d1 - sigma * math.sqrt(T)

