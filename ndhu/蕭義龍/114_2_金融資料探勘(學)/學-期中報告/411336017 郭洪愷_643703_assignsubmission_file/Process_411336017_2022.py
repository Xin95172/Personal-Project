def bs_price(S, K, T, r, sigma, cp_flag):
    """計算 Black-Scholes 理論價"""
    # 【極重要防呆】若 T<=0 則分母會有 sqrt(0) 導致 zero division，直接回傳 NaN
    if T <= 0 or sigma <= 0:
        return np.nan

    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    if cp_flag == 'C':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def calculate_iv_bisection(market_price, S, K, T, r, cp_flag, tol=1e-5, max_iter=100):
    """利用二分法反推隱含波動率 (IV)"""
    if T <= 0:
        return np.nan
    if pd.isna(market_price) or pd.isna(S) or pd.isna(K) or pd.isna(r) or market_price <= 0:
        return np.nan

    low, high = 1e-4, 5.0 # 設定 IV 搜尋範圍 0.01% ~ 500%

    for _ in range(max_iter):
        mid = (low + high) / 2
        price_mid = bs_price(S, K, T, r, mid, cp_flag)

        if pd.isna(price_mid):
            return np.nan

        if abs(price_mid - market_price) < tol:
            return mid

        if price_mid < market_price:
            low = mid
        else:
            high = mid

    return (low + high) / 2

