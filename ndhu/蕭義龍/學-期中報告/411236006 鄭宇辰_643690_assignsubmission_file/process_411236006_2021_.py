# 2. Black-Scholes 模型函數
# =================================================================
def bs_price(S, K, T, r, sigma, cp_flag):
    if T <= 0 or sigma <= 0:
        return max(0.0, S - K) if cp_flag == 'C' else max(0.0, K - S)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if cp_flag == 'C':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def find_iv_combined(market_price, S, K, T, r, cp_flag):
    intrinsic_val = max(0, S - K) if cp_flag == 'C' else max(0, K - S)
    if market_price <= intrinsic_val: return 0.0
    low, high = 0.0001, 5.0
    for _ in range(100):
        mid = (low + high) / 2
        price = bs_price(S, K, T, r, mid, cp_flag)
        if abs(market_price - price) < 1e-5: return mid
        if price < market_price: low = mid
        else: high = mid
    return mid

