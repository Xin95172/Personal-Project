print("\n--- 開始執行全年度資料分析 (含 IV 標準差統計) ---")

try:
    df_index = pd.read_csv(index_file_path, encoding='utf-8-sig')
except:
    df_index = pd.read_csv(index_file_path, encoding='cp950')

df_index.columns = df_index.columns.str.strip()
summary_list = []

for index, row in df_index.iterrows():
    date_str = pd.to_datetime(row['Date']).strftime('%Y%m%d')
    file_name = f"o{date_str}.csv"
    file_path = os.path.join(data_base_path, file_name)
    target_contract = str(row['Contract']).split('.')[0].strip()
    S0, rf, T = float(row['S0']), float(row['Rf']), float(row['Maturity'])/365.0

    if os.path.exists(file_path):
        try:
            try:
                df = pd.read_csv(file_path, encoding='utf-8-sig', low_memory=False)
            except:
                df = pd.read_csv(file_path, encoding='cp950', low_memory=False)

            df.columns = df.columns.str.replace(r'\s+', '', regex=True)
            for c in ['成交數量(BorS)', '履約價格', '成交價格']:
                df[c] = pd.to_numeric(df[c], errors='coerce')

            df['商品代號'] = df['商品代號'].astype(str).str.strip()
            df['買賣權別'] = df['買賣權別'].astype(str).str.strip().str.upper()
            df['到期月份(週別)'] = df['到期月份(週別)'].astype(str).str.split('.').str[0].str.strip()

            base_mask = (df['商品代號'] == 'TXO') & (df['成交數量(BorS)'] > 30) & \
                        (df['到期月份(週別)'] == target_contract) & (df['成交價格'] > 0)

            # 分別提取資料
            c_df = df[base_mask & df['買賣權別'].str.contains('C|買')].copy()
            p_df = df[base_mask & df['買賣權別'].str.contains('P|賣')].copy()

            # 計算 IV
            c_iv = c_df.apply(lambda x: find_iv_combined(x['成交價格'], S0, x['履約價格'], T, rf, 'C'), axis=1) if not c_df.empty else pd.Series(dtype=float)
            p_iv = p_df.apply(lambda x: find_iv_combined(x['成交價格'], S0, x['履約價格'], T, rf, 'P'), axis=1) if not p_df.empty else pd.Series(dtype=float)

            # 統計數值
            c_vol, p_vol = c_df['成交數量(BorS)'].sum(), p_df['成交數量(BorS)'].sum()

            summary_list.append({
                'Date': row['Date'],
                'S0': S0,
                'Call_Vol': c_vol,
                'Put_Vol': p_vol,
                'PCR': p_vol / c_vol if c_vol > 0 else np.nan,
                # Call IV 統計
                'Call_IV_Mean': c_iv.mean(),
                'Call_IV_Std': c_iv.std(),  # 標準差
                'Call_IV_Weighted': np.average(c_iv, weights=c_df['成交數量(BorS)']) if not c_iv.empty else np.nan,
                # Put IV 統計
                'Put_IV_Mean': p_iv.mean(),
                'Put_IV_Std': p_iv.std(),   # 標準差
                'Put_IV_Weighted': np.average(p_iv, weights=p_df['成交數量(BorS)']) if not p_iv.empty else np.nan
            })
            print(f"處理完成: {date_str}")
        except Exception as e:
            print(f"跳過 {date_str}，錯誤: {e}")
    else:
        print(f"跳過 {date_str} (檔案不存在)")

